#!/usr/bin/env node
// Theme guard (IMPLEMENTATION_PLAN.md, U9). Runs as part of `npm run lint`.
//
// 1. No raw colour values in stylesheets: every colour comes from the tokens in
//    src/styles/_tokens.scss (emitted as --pp-*) or from Material's --mat-sys-*.
// 2. Every documented token pair meets its WCAG contrast minimum in both themes.

import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(import.meta.url), '..', '..');
const TOKENS_FILE = join(root, 'src/styles/_tokens.scss');
const SCAN_DIRS = [join(root, 'src/app'), join(root, 'src/styles.scss')];
// Generated by `ng generate @angular/material:theme-color`; tonal palettes, not UI colours.
const EXEMPT = new Set([TOKENS_FILE, join(root, 'src/styles/_theme-colors.scss')]);

const errors = [];

// ---------------------------------------------------------------------------
// Tokens
// ---------------------------------------------------------------------------
const COLOUR = String.raw`#[0-9a-fA-F]{6}|rgb\([^)]*\)`;
const LINE = new RegExp(String.raw`^\s*([a-z0-9-]+):\s*\((${COLOUR}),\s*(${COLOUR})\),\s*$`);

const tokens = {};
for (const line of readFileSync(TOKENS_FILE, 'utf8').split('\n')) {
  const m = line.match(LINE);
  if (m) tokens[m[1]] = { light: m[2], dark: m[3] };
}
if (Object.keys(tokens).length < 20) {
  errors.push(`Parsed only ${Object.keys(tokens).length} tokens from ${relative(root, TOKENS_FILE)}; the "name: (light, dark)," format may have changed.`);
}

const toRgb = (value) => {
  if (value.startsWith('#')) {
    const h = value.slice(1);
    return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  }
  throw new Error(`Contrast pairs must use opaque hex tokens, got ${value}`);
};
const luminance = (value) =>
  toRgb(value)
    .map((v) => v / 255)
    .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
    .reduce((sum, v, i) => sum + v * [0.2126, 0.7152, 0.0722][i], 0);
export const contrast = (a, b) => {
  const [x, y] = [luminance(a), luminance(b)];
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
};

const TEXT = 4.5;
const NON_TEXT = 3;
// [foreground, background, minimum] — every pair the UI actually renders.
const PAIRS = [
  ['text', 'bg', TEXT],
  ['text', 'surface', TEXT],
  ['text', 'surface-raised', TEXT],
  ['text', 'surface-sunken', TEXT],
  ['text', 'bar', TEXT],
  ['text-strong', 'bg', TEXT],
  ['text-strong', 'surface', TEXT],
  ['text-muted', 'bg', TEXT],
  ['text-muted', 'surface', TEXT],
  ['text-muted', 'surface-raised', TEXT],
  ['text-muted', 'bar', TEXT],
  ['accent', 'bg', TEXT],
  ['accent', 'surface', TEXT],
  ['accent', 'surface-raised', TEXT],
  ['on-accent', 'accent-fill', TEXT],
  ['on-accent-text', 'accent', TEXT], // Material on-primary on primary
  ['bg', 'text-strong', TEXT], // inverse-on-surface on inverse-surface (snackbars, tooltips)
  ['inverse-accent', 'text-strong', TEXT], // inverse-primary on inverse-surface
  ['on-accent-subtle', 'accent-subtle', TEXT],
  ['status-expired', 'status-expired-bg', TEXT],
  ['status-expired', 'surface', TEXT],
  ['status-expired', 'bg', TEXT],
  ['status-soon', 'status-soon-bg', TEXT],
  ['status-ok', 'status-ok-bg', TEXT],
  ['status-ok', 'surface', TEXT],
  ['info', 'info-bg', TEXT],
  ['info', 'surface', TEXT],
  ['focus', 'bg', NON_TEXT],
  ['focus', 'surface', NON_TEXT],
  ['input-border', 'bg', NON_TEXT],
  ['input-border', 'surface', NON_TEXT],
  ['macro-calories', 'surface', NON_TEXT],
  ['macro-protein', 'surface', NON_TEXT],
  ['macro-carbs', 'surface', NON_TEXT],
  ['macro-fat', 'surface', NON_TEXT],
];

for (const [fg, bg, min] of PAIRS) {
  for (const mode of ['light', 'dark']) {
    if (!tokens[fg] || !tokens[bg]) {
      errors.push(`Contrast pair ${fg} on ${bg}: token missing`);
      continue;
    }
    const ratio = contrast(tokens[fg][mode], tokens[bg][mode]);
    if (ratio < min) {
      errors.push(`Contrast ${mode}: ${fg} (${tokens[fg][mode]}) on ${bg} (${tokens[bg][mode]}) is ${ratio.toFixed(2)}:1, needs ${min}:1`);
    }
  }
}

// ---------------------------------------------------------------------------
// Single-valued colours outside CSS must match the `bar` / `bg` tokens
// ---------------------------------------------------------------------------
const read = (rel) => readFileSync(join(root, rel), 'utf8');
const expectEqual = (where, actual, expected) => {
  if ((actual ?? '').toLowerCase() !== expected.toLowerCase()) errors.push(`${where} is ${actual}, expected ${expected}`);
};
if (tokens.bar && tokens.bg) {
  const manifest = JSON.parse(read('src/manifest.webmanifest'));
  expectEqual('manifest theme_color', manifest.theme_color, tokens.bar.dark);
  expectEqual('manifest background_color', manifest.background_color, tokens.bg.dark);
  expectEqual('index.html theme-color', read('src/index.html').match(/name="theme-color" content="([^"]+)"/)?.[1], tokens.bar.dark);
  expectEqual('index.html boot script light bar', read('src/index.html').match(/content='(#[0-9a-fA-F]{6})'/)?.[1], tokens.bar.light);
  const bar = read('src/app/core/services/theme.service.ts').match(/dark: '([^']+)', light: '([^']+)'/);
  expectEqual('ThemeService dark bar', bar?.[1], tokens.bar.dark);
  expectEqual('ThemeService light bar', bar?.[2], tokens.bar.light);
}

// ---------------------------------------------------------------------------
// Raw colours in stylesheets
// ---------------------------------------------------------------------------
const RAW = /#[0-9a-fA-F]{3,8}\b|(?<![\w-])(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color-mix)\(|(?<![\w-])(?:white|black)(?![\w-])/;

const walk = (path) => {
  if (statSync(path).isDirectory()) return readdirSync(path).flatMap((f) => walk(join(path, f)));
  return path.endsWith('.scss') ? [path] : [];
};

for (const file of SCAN_DIRS.flatMap(walk)) {
  if (EXEMPT.has(file)) continue;
  const source = readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[^\n]/g, ' '));
  source.split('\n').forEach((line, i) => {
    const code = line.replace(/\/\/.*$/, '');
    if (RAW.test(code)) errors.push(`${relative(root, file)}:${i + 1}: raw colour, use a --pp-* token: ${code.trim()}`);
  });
}

// ---------------------------------------------------------------------------
// Every custom property used in a stylesheet is defined somewhere. An
// undefined var() silently falls back to nothing (the calendar cells were
// transparent for that reason), and Material 21 no longer reads --mdc-*.
// ---------------------------------------------------------------------------
const allScss = [join(root, 'src')].flatMap(walk);
const defined = new Set(Object.keys(tokens).map((n) => `--pp-${n}`));
for (const file of allScss) {
  for (const m of readFileSync(file, 'utf8').matchAll(/(--[a-z0-9-]+)\s*:/g)) defined.add(m[1]);
}
for (const file of allScss) {
  readFileSync(file, 'utf8').split('\n').forEach((line, i) => {
    for (const m of line.replace(/\/\/.*$/, '').matchAll(/var\((--[a-z0-9-]+)/g)) {
      const name = m[1];
      if (name.startsWith('--mdc-')) errors.push(`${relative(root, file)}:${i + 1}: ${name} is not read by Material 21; use the --mat-* token`);
      else if (!name.startsWith('--mat-') && !defined.has(name)) errors.push(`${relative(root, file)}:${i + 1}: ${name} is not defined anywhere`);
    }
  });
}

if (errors.length) {
  console.error(`Theme check failed (${errors.length}):\n- ${errors.join('\n- ')}`);
  process.exit(1);
}
console.log(`Theme check passed: ${Object.keys(tokens).length} tokens, ${PAIRS.length * 2} contrast pairs, no raw colours.`);
